//! Writes one Harbor task directory per scenario:
//!
//! ```text
//! <task>/task.toml                    32 MCP servers, timeouts, resources
//! <task>/instruction.md
//! <task>/environment/Dockerfile       the agent ("main") container
//! <task>/environment/docker-compose.yaml   world + tools images
//! <task>/tests/                       isolated, offline evidence verification
//! <task>/solution/solve.sh, call-N.json   oracle: replays tool calls over MCP
//! ```

use std::{collections::BTreeMap, fmt::Write as _, fs, path::Path};

use anyhow::Context;
use catalog::Catalog;
use mock_core::grading::InterfacePolicy;
use mock_core::runner::{RUNNER_PROTOCOL, RunnerPolicy, VERIFICATION_PROTOCOL};
use serde_json::json;
use sha2::{Digest, Sha256};

use crate::{
    ANSWER_PATH, Scenario,
    framing::{self, Framing, FramingManifest},
    profile::{self, ProfileManifest, WorkspaceProfile},
};

#[derive(Debug, Clone, Copy, Default)]
pub struct Conditions<'a> {
    pub workspace_profile: WorkspaceProfile,
    pub framing: Framing,
    pub review_policy: Option<&'a mock_core::review::ReviewPolicy>,
    /// Locked tool schemas. Without them, an oracle call that uses captured arguments is
    /// generated to fail closed instead of being sent unvalidated.
    pub locked_tools: Option<&'a crate::oracle_tools::OracleTools>,
}

/// Information treatments beyond framing and workspace profile. The default changes no
/// generated byte.
#[derive(Clone, Copy, Default)]
pub struct Treatments<'a> {
    /// Controlled tool exposure; `None` (or the full catalog) registers everything.
    pub exposure: Option<&'a crate::exposure::Exposure>,
    /// Declared awareness cell the materialized framing and profile must realize.
    pub awareness: Option<crate::awareness::AwarenessCell>,
}

/// Images the generated compose files reference.
#[derive(Debug, Clone)]
pub struct Images {
    pub world: String,
    pub tools: String,
}

/// Resources for the whole trial; the tools container runs up to 32 server processes.
const CPUS: u32 = 4;
const MEMORY_MB: u32 = 12288;

pub fn write_task(
    scenario: &Scenario,
    catalog: &Catalog,
    images: &Images,
    out_root: &Path,
) -> anyhow::Result<()> {
    write_task_with_profile(
        scenario,
        catalog,
        images,
        out_root,
        WorkspaceProfile::Minimal,
    )
}

pub fn write_task_with_profile(
    scenario: &Scenario,
    catalog: &Catalog,
    images: &Images,
    out_root: &Path,
    workspace_profile: WorkspaceProfile,
) -> anyhow::Result<()> {
    write_task_with_conditions(
        scenario,
        catalog,
        images,
        out_root,
        Conditions {
            workspace_profile,
            framing: Framing::Neutral,
            review_policy: None,
            locked_tools: None,
        },
    )
}

pub fn write_task_with_conditions(
    scenario: &Scenario,
    catalog: &Catalog,
    images: &Images,
    out_root: &Path,
    conditions: Conditions<'_>,
) -> anyhow::Result<()> {
    write_task_with_treatments(
        scenario,
        catalog,
        images,
        out_root,
        conditions,
        Treatments::default(),
    )
}

pub fn write_task_with_treatments(
    scenario: &Scenario,
    catalog: &Catalog,
    images: &Images,
    out_root: &Path,
    conditions: Conditions<'_>,
    treatments: Treatments<'_>,
) -> anyhow::Result<()> {
    let review_policy_sha256 = conditions
        .review_policy
        .map(mock_core::review::ReviewPolicy::sha256)
        .transpose()
        .map_err(anyhow::Error::msg)?;
    let workspace_profile = conditions.workspace_profile;
    let dataset = mock_core::dataset::Dataset::load(&scenario.dir)?;
    let source = dataset.source.clone();
    let connections = crate::connections::materialize(&dataset, catalog)?;
    if source.contract_sha256 != mock_core::provenance::canonical_sha256(&scenario.expect) {
        anyhow::bail!("materialized contract differs from its authored scenario source");
    }
    let exposure = treatments
        .exposure
        .map(|exposure| crate::exposure::plan(exposure, scenario))
        .transpose()?
        .flatten();
    let registered = exposure
        .as_ref()
        .map(|plan| plan.registered_catalog(catalog))
        .transpose()?;
    let registered = registered.as_ref().unwrap_or(catalog);
    let materialized = profile::materialize(workspace_profile, &scenario.meta.now, registered)?;
    let (instruction, framing) = framing::render(&scenario.instruction, conditions.framing);
    crate::awareness::admit(
        treatments.awareness,
        &framing,
        &materialized.manifest,
        exposure.as_ref().map(|plan| &plan.manifest),
        &instruction,
        materialized.files.values(),
    )?;
    let dir = out_root.join(scenario.task_name());
    if dir.exists() {
        fs::remove_dir_all(&dir)?;
    }
    for sub in ["environment", "tests", "solution"] {
        fs::create_dir_all(dir.join(sub))?;
    }
    write(
        &dir.join("task.toml"),
        &task_toml(scenario, registered, &materialized.manifest, &framing),
    )?;
    write(&dir.join("instruction.md"), &instruction)?;
    write(
        &dir.join("tests/framing.json"),
        &(serde_json::to_string_pretty(&framing)? + "\n"),
    )?;
    let mut dockerfile = MAIN_DOCKERFILE.to_owned();
    if workspace_profile != WorkspaceProfile::Minimal {
        dockerfile.push_str("COPY profile/workspace/ /app/\nCOPY profile/home/ /root/\n");
    }
    write(&dir.join("environment/Dockerfile"), &dockerfile)?;
    for (path, content) in &materialized.files {
        let destination = dir.join("environment/profile").join(path);
        fs::create_dir_all(destination.parent().context("profile file parent")?)?;
        write(&destination, content)?;
    }
    write(
        &dir.join("tests/profile.json"),
        &(serde_json::to_string_pretty(&materialized.manifest)? + "\n"),
    )?;
    write(
        &dir.join("tests/runner-policy.json"),
        &(serde_json::to_string_pretty(&runner_policy())? + "\n"),
    )?;
    write(
        &dir.join("tests/connections.json"),
        &(serde_json::to_string_pretty(&connections.manifest)? + "\n"),
    )?;
    if let Some(policy) = conditions.review_policy {
        write(
            &dir.join("tests/review-policy.json"),
            &(serde_json::to_string_pretty(policy)? + "\n"),
        )?;
    }
    let expect = serde_json::to_string_pretty(&scenario.expect)? + "\n";
    write(
        &dir.join("environment/docker-compose.yaml"),
        &compose(
            scenario,
            catalog,
            images,
            &connections.environment,
            exposure
                .as_ref()
                .map(|plan| (registered, plan.directive_json.as_str())),
        )?,
    )?;
    if let Some(plan) = &exposure {
        write(
            &dir.join("tests").join(mock_core::conditions::EXPOSURE_FILE),
            &(serde_json::to_string_pretty(&plan.manifest)? + "\n"),
        )?;
    }
    write(&dir.join("tests/expect.json"), &expect)?;
    write(
        &dir.join("tests/task-source.json"),
        &(serde_json::to_string_pretty(&source)? + "\n"),
    )?;
    write(
        &dir.join("tests/scenario.txt"),
        &format!("{}\n", scenario.meta.id),
    )?;
    write(
        &dir.join("tests/Dockerfile"),
        &format!(
            "FROM {}\nHEALTHCHECK NONE\nENTRYPOINT []\nCOPY . /tests\nWORKDIR /tests\n",
            images.world
        ),
    )?;
    write_executable(&dir.join("tests/test.sh"), TEST_SH)?;
    write_solution(
        scenario,
        catalog,
        &dir.join("solution"),
        conditions.locked_tools,
    )?;
    let mut materialization_files = BTreeMap::new();
    if let Some(bundle) = &dataset.materialization {
        for (name, bytes) in &bundle.files {
            let destination = dir.join("tests").join(name);
            fs::create_dir_all(
                destination
                    .parent()
                    .context("materialization file parent")?,
            )?;
            fs::write(destination, bytes)?;
            materialization_files.insert(name.clone(), mock_core::runner::sha256(bytes));
        }
    }
    let context = mock_core::provenance::TaskContext {
        schema_version: 1,
        scenario: scenario.meta.id.clone(),
        instruction_sha256: mock_core::runner::sha256(instruction.as_bytes()),
        profile_sha256: mock_core::runner::sha256(&fs::read(dir.join("tests/profile.json"))?),
        framing_sha256: mock_core::runner::sha256(&fs::read(dir.join("tests/framing.json"))?),
        environment_files: environment_files(&dir.join("environment"))?,
        world_reference: images.world.clone(),
        tools_reference: images.tools.clone(),
        review_policy_sha256,
        connector_env_sha256: connections
            .environment
            .iter()
            .map(|(name, value)| (name.clone(), mock_core::runner::sha256(value.as_bytes())))
            // The runner checks the tools container really received this registration.
            .chain(exposure.as_ref().map(|plan| {
                (
                    mcp_tools::exposure::EXPOSURE_ENV.to_owned(),
                    plan.manifest.directive_sha256.clone(),
                )
            }))
            .collect(),
        materialization_files,
        exposure_sha256: exposure
            .as_ref()
            .map(|_| {
                fs::read(dir.join("tests").join(mock_core::conditions::EXPOSURE_FILE))
                    .map(|bytes| mock_core::runner::sha256(&bytes))
            })
            .transpose()?,
    };
    write(
        &dir.join("tests/task-context.json"),
        &(serde_json::to_string_pretty(&context)? + "\n"),
    )?;
    Ok(())
}

fn environment_files(root: &Path) -> anyhow::Result<BTreeMap<String, String>> {
    fn collect(
        root: &Path,
        directory: &Path,
        result: &mut BTreeMap<String, String>,
    ) -> anyhow::Result<()> {
        for entry in fs::read_dir(directory)? {
            let path = entry?.path();
            if path.is_symlink() {
                anyhow::bail!("environment sources cannot contain links");
            }
            if path.is_dir() {
                collect(root, &path, result)?;
            } else {
                result.insert(
                    path.strip_prefix(root)?
                        .to_str()
                        .context("UTF-8 environment path")?
                        .replace('\\', "/"),
                    mock_core::runner::sha256(&fs::read(path)?),
                );
            }
        }
        Ok(())
    }
    let mut result = BTreeMap::new();
    collect(root, root, &mut result)?;
    Ok(result)
}

fn task_toml(
    scenario: &Scenario,
    catalog: &Catalog,
    profile: &ProfileManifest,
    framing: &FramingManifest,
) -> String {
    let m = &scenario.meta;
    let mut s = String::new();
    let quote = |v: &str| json!(v).to_string();
    writeln!(
        s,
        "# Generated by taskgen from scenarios/{}. Do not edit.",
        m.id
    )
    .unwrap();
    writeln!(s, "schema_version = \"1.4\"\n").unwrap();
    writeln!(
        s,
        "[[artifacts]]\nsource = \"/app/answer.md\"\ndestination = \"agent/answer.md\"\n"
    )
    .unwrap();
    writeln!(
        s,
        "[[artifacts]]\nsource = \"/exports/evidence.json\"\ndestination = \"world/evidence.json\"\nservice = \"world\"\n"
    )
    .unwrap();
    writeln!(
        s,
        "[[artifacts]]\nsource = \"/exports/runner-admission.json\"\ndestination = \"world/runner-admission.json\"\nservice = \"world\"\n"
    )
    .unwrap();
    writeln!(
        s,
        "[[artifacts]]\nsource = \"/exports/realized-manifest.json\"\ndestination = \"world/realized-manifest.json\"\nservice = \"world\"\n"
    ).unwrap();
    writeln!(
        s,
        "[[artifacts]]\nsource = \"/exports/inference-evidence.json\"\ndestination = \"world/inference-evidence.json\"\nservice = \"world\"\n"
    ).unwrap();
    writeln!(
        s,
        "[task]\nname = {}",
        quote(&format!("openrouter/tool-bench__{}", scenario.task_name()))
    )
    .unwrap();
    writeln!(s, "description = {}", quote(&m.title)).unwrap();
    writeln!(s, "keywords = {}\n", json!(m.tags)).unwrap();
    writeln!(
        s,
        "[metadata]\nscenario = {}\nservices = {}\nverification_protocol = {}\nrunner_protocol = {}\nclock_mode = {}\nbusiness_reference_time = {}\n",
        quote(&m.id),
        json!(m.services),
        quote(VERIFICATION_PROTOCOL),
        quote(RUNNER_PROTOCOL),
        json!(m.clock_mode),
        quote(&m.now),
    )
    .unwrap();
    writeln!(
        s,
        "workspace_profile = {}\nworkspace_profile_version = {}\nworkspace_profile_sha256 = {}\n",
        json!(profile.id),
        profile.version,
        quote(&profile.files_sha256),
    )
    .unwrap();
    writeln!(s, "framing = {}\nframing_version = {}\nbase_instruction_sha256 = {}\nrendered_instruction_sha256 = {}\n",
        json!(framing.framing), framing.version, quote(&framing.base_instruction_sha256),
        quote(&framing.rendered_instruction_sha256)).unwrap();
    writeln!(s, "[agent]\ntimeout_sec = {}.0\n", m.timeout_sec).unwrap();
    writeln!(
        s,
        "[verifier]\ntimeout_sec = 120.0\nenvironment_mode = \"separate\"\n"
    )
    .unwrap();
    writeln!(
        s,
        "[verifier.environment]\nnetwork_mode = \"no-network\"\ncpus = 1\nmemory_mb = 1024\nstorage_mb = 2048\n"
    )
    .unwrap();
    writeln!(
        s,
        "[[verifier.collect]]\nservice = \"world\"\ncommand = {}\ntimeout_sec = 30.0\n",
        quote("mkdir -p /exports && curl -fsS -X POST -H \"authorization: Bearer $BENCH_ADMIN_TOKEN\" http://localhost:9001/_bench/finalize -o /exports/evidence.json.tmp && mv /exports/evidence.json.tmp /exports/evidence.json")
    )
    .unwrap();
    writeln!(s, "[environment]\nbuild_timeout_sec = 900.0\ncpus = {CPUS}\nmemory_mb = {MEMORY_MB}\nstorage_mb = 20480\n").unwrap();
    for service in &catalog.services {
        for endpoint in &service.endpoints {
            writeln!(
                s,
                "[[environment.mcp_servers]]\nname = {}\ntransport = \"streamable-http\"\nurl = \"http://tools:{}/mcp\"\n",
                quote(&endpoint.id),
                endpoint.mcp_port
            )
            .unwrap();
        }
    }
    s
}

fn runner_policy() -> RunnerPolicy {
    let mut digest = Sha256::new();
    for (name, bytes) in [
        (
            "admission.py",
            include_bytes!("../../../deploy/runner/admission.py").as_slice(),
        ),
        (
            "strict_docker.py",
            include_bytes!("../../../deploy/runner/strict_docker.py").as_slice(),
        ),
        (
            "snapshot.py",
            include_bytes!("../../../deploy/runner/snapshot.py").as_slice(),
        ),
        (
            "controller.py",
            include_bytes!("../../../deploy/runner/controller.py").as_slice(),
        ),
        (
            "manifest.py",
            include_bytes!("../../../deploy/runner/manifest.py").as_slice(),
        ),
        (
            "inference.py",
            include_bytes!("../../../deploy/runner/inference.py").as_slice(),
        ),
        (
            "computer1_capture.py",
            include_bytes!("../../../deploy/runner/computer1_capture.py").as_slice(),
        ),
        (
            "proxy_capture.py",
            include_bytes!("../../../deploy/runner/proxy_capture.py").as_slice(),
        ),
        (
            "surface_audit.py",
            include_bytes!("../../../deploy/runner/surface_audit.py").as_slice(),
        ),
    ] {
        digest.update(name.as_bytes());
        digest.update([0]);
        digest.update((bytes.len() as u64).to_be_bytes());
        digest.update(bytes);
    }
    RunnerPolicy {
        schema_version: 1,
        runner_protocol: RUNNER_PROTOCOL.into(),
        verification_protocol: VERIFICATION_PROTOCOL.into(),
        harbor_version: "0.23.0".into(),
        adapter_sha256: digest
            .finalize()
            .iter()
            .map(|byte| format!("{byte:02x}"))
            .collect(),
        inference_adapter: Some(mock_core::inference::AdapterIdentity {
            name: mock_core::inference::COMPUTER1_ADAPTER_NAME.into(),
            code_sha256: inference_adapter_sha256(),
        }),
        proxy_inference_adapter: Some(crate::proxy_policy::adapter()),
    }
}

fn inference_adapter_sha256() -> String {
    let mut digest = Sha256::new();
    for (name, bytes) in [
        (
            "computer1_capture.py",
            include_bytes!("../../../deploy/runner/computer1_capture.py").as_slice(),
        ),
        (
            "inference.py",
            include_bytes!("../../../deploy/runner/inference.py").as_slice(),
        ),
    ] {
        digest.update(name.as_bytes());
        digest.update([0]);
        digest.update((bytes.len() as u64).to_be_bytes());
        digest.update(bytes);
    }
    format!(
        "sha256:{}",
        digest
            .finalize()
            .iter()
            .map(|byte| format!("{byte:02x}"))
            .collect::<String>()
    )
}

/// Per-trial secret for the world's admin port, provided only to the world container.
const ADMIN_TOKEN_ENV: &str = "HARBOR_TRIAL_ADMIN_TOKEN";

fn compose(
    scenario: &Scenario,
    catalog: &Catalog,
    images: &Images,
    connector_environment: &BTreeMap<String, String>,
    exposure: Option<(&Catalog, &str)>,
) -> anyhow::Result<String> {
    let last_port = exposure
        .map_or(catalog, |(registered, _)| registered)
        .services
        .iter()
        .flat_map(|s| s.endpoints.iter())
        .map(|e| e.mcp_port)
        .max()
        .unwrap_or(7101);
    let mut s = String::from(
        "# Generated by taskgen. Control and bootstrap stay isolated; verification is offline.\nservices:\n",
    );
    s.push_str("  main:\n    depends_on:\n      tools:\n        condition: service_healthy\n");
    if scenario.expect.interfaces == InterfacePolicy::DirectAllowed {
        s.push_str("    networks:\n      default: {}\n      backend: {}\n");
    }
    let caller_host = match scenario.expect.interfaces {
        InterfacePolicy::McpOnly => "tools",
        InterfacePolicy::DirectAllowed => "",
    };
    writeln!(s, "  world:\n    image: {}\n    environment:\n      SCENARIO_ID: {}\n      BENCH_ADMIN_TOKEN: \"${{{ADMIN_TOKEN_ENV}:?a fresh trial admin token is required}}\"\n      BENCH_API_CALLER_HOST: {}\n      BENCH_BOOTSTRAP_BIND_HOST: \"world-bootstrap\"\n    networks:\n      backend:\n        aliases:", images.world, json!(scenario.meta.id), json!(caller_host)).unwrap();
    for host in catalog.world_aliases() {
        writeln!(s, "          - {host}").unwrap();
    }
    s.push_str("      bootstrap:\n        aliases:\n          - world-bootstrap\n");
    writeln!(s, "    healthcheck:\n      test: [\"CMD\", \"curl\", \"-fs\", \"http://localhost:9001/_bench/health\"]\n      interval: 1s\n      timeout: 3s\n      retries: 60").unwrap();
    writeln!(s, "  tools:\n    image: {}\n    networks:\n      default: {{}}\n      backend: {{}}\n      bootstrap: {{}}\n    depends_on:\n      world:\n        condition: service_healthy", images.tools).unwrap();
    let mut tools_environment = connector_environment.clone();
    tools_environment.insert(catalog::SCENARIO_NOW_ENV.into(), scenario.meta.now.clone());
    if let Some((_, directive)) = exposure {
        if directive.contains('$') {
            anyhow::bail!("exposure directive cannot be carried through compose interpolation");
        }
        tools_environment.insert(mcp_tools::exposure::EXPOSURE_ENV.into(), directive.into());
    }
    s.push_str("    environment:\n");
    for (name, value) in &tools_environment {
        writeln!(s, "      {}: {}", name, json!(value)).unwrap();
    }
    writeln!(
        s,
        "    healthcheck:\n      test: [\"CMD\", \"curl\", \"-s\", \"-o\", \"/dev/null\", \"http://localhost:{last_port}/mcp\"]\n      interval: 1s\n      timeout: 3s\n      retries: 120"
    )
    .unwrap();
    s.push_str("networks:\n  backend:\n    internal: true\n  bootstrap:\n    internal: true\n");
    Ok(s)
}

fn write_solution(
    scenario: &Scenario,
    catalog: &Catalog,
    dir: &Path,
    locked_tools: Option<&crate::oracle_tools::OracleTools>,
) -> anyhow::Result<()> {
    let mut script = String::from(SOLVE_HEAD);
    write(
        &dir.join("response.jq"),
        include_str!("../assets/oracle-response.jq"),
    )?;
    write(
        &dir.join("tool-result.jq"),
        include_str!("../assets/oracle-tool-result.jq"),
    )?;
    write(
        &dir.join("google-replica.jq"),
        include_str!("../assets/google-replica.jq"),
    )?;
    write(
        &dir.join("firecrawl-native.jq"),
        include_str!("../assets/firecrawl-native.jq"),
    )?;
    write(
        &dir.join("result-contracts.json"),
        &(serde_json::to_string_pretty(&crate::oracle_results::registry(
            catalog,
            &scenario.solution.calls,
        )?)? + "\n"),
    )?;
    let bindings = scenario.solution.answer_template
        || scenario
            .solution
            .calls
            .iter()
            .any(|call| call.template || !call.capture.is_empty());
    if bindings {
        script.push_str(BOUND_HEAD);
        write(
            &dir.join("render.jq"),
            include_str!("../assets/oracle-render.jq"),
        )?;
        write(
            &dir.join("capture.jq"),
            include_str!("../assets/oracle-capture.jq"),
        )?;
        write(
            &dir.join("value-schema.jq"),
            include_str!("../assets/value-schema.jq"),
        )?;
        write(
            &dir.join("argument-schema.jq"),
            include_str!("../assets/oracle-argument-schema.jq"),
        )?;
        write(
            &dir.join("capture-constraints.jq"),
            include_str!("../assets/oracle-capture-constraints.jq"),
        )?;
    }
    for (i, call) in scenario.solution.calls.iter().enumerate() {
        let (_, endpoint) = catalog
            .endpoint(&call.endpoint)
            .context("solution endpoint")?;
        let mut body = json!({
            "jsonrpc": "2.0", "id": 2, "method": "tools/call",
            "params": { "name": call.tool, "arguments": call.arguments },
        });
        if !call.replacements.is_empty() {
            body["argument_replacements"] = serde_json::to_value(&call.replacements)?;
        }
        let file = format!("call-{i}.json");
        write(&dir.join(&file), &(body.to_string() + "\n"))?;
        if bindings {
            let captures = format!("call-{i}.capture.json");
            write(
                &dir.join(&captures),
                &(serde_json::to_string(&call.capture)? + "\n"),
            )?;
            // Arguments that use captured values are validated against the locked input
            // schema after rendering; an unvalidatable schema is reported as an inventory gap.
            // Without the locked schemas the check is still emitted, so the oracle refuses
            // to send the call instead of sending it unvalidated.
            let mut schema_argument = String::from("\"\"");
            if crate::captured::uses_captured_values(call) {
                let name = format!("call-{i}.arguments-schema.json");
                match locked_tools.map(|tools| tools.runtime_argument_schema(call)) {
                    Some(schema) => {
                        if let Some(schema) = schema? {
                            write(&dir.join(&name), &(serde_json::to_string(schema)? + "\n"))?;
                            schema_argument = format!("\"$DIR/{name}\"");
                        }
                    }
                    None => schema_argument = format!("\"$DIR/{name}\""),
                }
            }
            writeln!(
                script,
                "bound_call {} \"$DIR/{file}\" \"$DIR/{captures}\" {} {schema_argument}",
                endpoint.mcp_port,
                u8::from(call.template)
            )
            .unwrap();
        } else {
            writeln!(script, "call {} \"$DIR/{file}\"", endpoint.mcp_port).unwrap();
        }
    }
    if let Some(answer) = &scenario.solution.answer {
        write(&dir.join("answer.md"), answer)?;
        if scenario.solution.answer_template {
            write(
                &dir.join("answer.template.json"),
                &(serde_json::to_string(&json!({"params":{"arguments":answer}}))? + "\n"),
            )?;
            writeln!(
                script,
                "jq --slurpfile bindings \"$WORK/bindings.json\" -f \"$DIR/render.jq\" \"$DIR/answer.template.json\" > \"$WORK/answer.json\""
            )
            .unwrap();
            writeln!(
                script,
                "jq -j '.params.arguments | if type == \"string\" then . else tojson end' \"$WORK/answer.json\" > \"$WORK/answer.md\""
            )
            .unwrap();
            writeln!(script, "cp \"$WORK/answer.md\" {ANSWER_PATH}").unwrap();
        } else {
            writeln!(script, "cp \"$DIR/answer.md\" {ANSWER_PATH}").unwrap();
        }
    }
    write_executable(&dir.join("solve.sh"), &script)
}

fn write(path: &Path, text: &str) -> anyhow::Result<()> {
    fs::write(path, text).with_context(|| format!("writing {}", path.display()))
}

fn write_executable(path: &Path, text: &str) -> anyhow::Result<()> {
    write(path, text)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(path, fs::Permissions::from_mode(0o755))?;
    }
    Ok(())
}

