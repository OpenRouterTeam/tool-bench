#!/usr/bin/env bash
# up.sh <task-name> <slot>
#
# Starts one task's `world` and `tools` containers as compose project tbpilot-<slot>, with a
# fresh admin token, and publishes tools port 71NN on 127.0.0.1:(20000 + slot*100 + NN).
# <task-name> is a directory under $PILOT_TASKS (default /tmp/tb-pilot/tasks) or an absolute
# path to a generated task directory. Operator state lives in /tmp/tb-pilot/slots/<slot>/;
# the acting agent gets /tmp/tb-pilot/agents/<slot>/ (the `mcp` command and its app/ directory).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
PILOT_HOME=/tmp/tb-pilot
PY="${PILOT_PYTHON:-$(command -v python3.13 || command -v python3.12 || command -v python3.11 || command -v python3)}"
die() { printf 'up.sh: %s\n' "$*" >&2; exit 2; }

[ $# -eq 2 ] || die "usage: up.sh <task-name> <slot>"
task="$1"
slot="$2"
case "$slot" in ''|*[!0-9]*) die "slot must be a number from 0 to 19" ;; esac
slot=$((10#$slot))
[ "$slot" -le 19 ] || die "slot must be a number from 0 to 19"
case "$task" in
  /*) task_dir="${task%/}" ;;
  *) task_dir="${PILOT_TASKS:-$PILOT_HOME/tasks}/$task" ;;
esac
for needed in task.toml instruction.md environment/docker-compose.yaml tests/test.sh; do
  [ -f "$task_dir/$needed" ] || die "$task_dir is not a generated task (no $needed); run prepare.sh or set PILOT_TASKS"
done

project="tbpilot-$slot"
slot_dir="$PILOT_HOME/slots/$slot"
agent_dir="$PILOT_HOME/agents/$slot"
if [ -n "$(docker ps -aq --filter "label=com.docker.compose.project=$project")" ]; then
  die "slot $slot is in use (compose project $project has containers); run down.sh $slot first"
fi
# A previous run that was graded is kept in the archive; anything else is discarded.
if [ -f "$slot_dir/verifier/assessment.json" ]; then
  # shellcheck disable=SC1091
  previous="$( (. "$slot_dir/slot.env" && printf '%s' "$TASK_NAME") 2> /dev/null || true)"
  mkdir -p "$PILOT_HOME/archive"
  mv "$slot_dir" "$PILOT_HOME/archive/$(date -u +%Y%m%dT%H%M%SZ)-slot$slot-$previous"
fi
rm -rf "$slot_dir" "$agent_dir"
mkdir -p "$slot_dir" "$agent_dir/app"

# Snapshot what compose and the verifier read, so regenerating tasks cannot change a live slot.
cp "$task_dir/environment/docker-compose.yaml" "$slot_dir/compose.yaml"
cp -R "$task_dir/tests" "$slot_dir/tests"
cp "$task_dir/instruction.md" "$slot_dir/instruction.md"

# The override publishes the tools ports and gives `main` (Harbor's agent container, which
# the task file declares with no image) a placeholder that is never started.
"$PY" - "$task_dir/task.toml" "$slot" "$slot_dir" <<'PYTHON'
import json, re, sys, tomllib

task_toml, slot, slot_dir = sys.argv[1], int(sys.argv[2]), sys.argv[3]
with open(task_toml, "rb") as handle:
    task = tomllib.load(handle)
servers, ports = [], []
for server in task["environment"]["mcp_servers"]:
    match = re.fullmatch(r"http://tools:(71\d\d)(/.*)", server["url"])
    if not match:
        sys.exit(f"up.sh: unexpected MCP server URL {server['url']!r}")
    port = int(match.group(1))
    host_port = 20000 + slot * 100 + (port - 7100)
    ports.append((host_port, port))
    servers.append({"name": server["name"], "url": f"http://127.0.0.1:{host_port}{match.group(2)}"})
lines = [
    "# Generated by deploy/pilot/up.sh.",
    "services:",
    "  main:",
    "    image: tbpilot/unused-agent-placeholder",
    "    profiles: [tbpilot-never]",
    "  tools:",
    "    ports:",
]
lines += [f'      - "127.0.0.1:{host}:{container}"' for host, container in sorted(ports)]
with open(f"{slot_dir}/compose.override.yaml", "w") as handle:
    handle.write("\n".join(lines) + "\n")
with open(f"{slot_dir}/servers.json", "w") as handle:
    json.dump({"servers": servers}, handle, indent=1)
    handle.write("\n")
PYTHON

token="$(openssl rand -hex 32)"
( umask 077
  {
    printf 'SLOT=%q\n' "$slot"
    printf 'PROJECT=%q\n' "$project"
    printf 'TASK_DIR=%q\n' "$task_dir"
    printf 'TASK_NAME=%q\n' "$(basename "$task_dir")"
    printf 'HARBOR_TRIAL_ADMIN_TOKEN=%q\n' "$token"
    printf 'STARTED_AT=%q\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  } > "$slot_dir/slot.env" )

# The agent prompt is the block between the agent-prompt markers in README.md.
awk '/<!-- agent-prompt:begin -->/{on=1;next} /<!-- agent-prompt:end -->/{on=0} on && !/^```/' \
  "$HERE/README.md" > "$slot_dir/agent-prompt.tmpl"
[ -s "$slot_dir/agent-prompt.tmpl" ] || die "README.md has no agent-prompt block"
"$PY" - "$slot_dir" "$agent_dir" <<'PYTHON'
import sys

slot_dir, agent_dir = sys.argv[1:3]
text = open(f"{slot_dir}/agent-prompt.tmpl").read()
instruction = open(f"{slot_dir}/instruction.md").read().strip()
for key, value in (("{MCP}", f"{agent_dir}/mcp"), ("{APP}", f"{agent_dir}/app"), ("{INSTRUCTION}", instruction)):
    text = text.replace(key, value)
open(f"{slot_dir}/agent-prompt.md", "w").write(text)
PYTHON
rm -f "$slot_dir/agent-prompt.tmpl"
# The agent's command: mcp.py with this slot selected.
printf '#!/bin/sh\nPILOT_SLOT=%s exec %q %q "$@"\n' "$slot" "$PY" "$HERE/mcp.py" > "$agent_dir/mcp"
chmod +x "$agent_dir/mcp"

compose() {
  HARBOR_TRIAL_ADMIN_TOKEN="$token" docker compose -p "$project" \
    -f "$slot_dir/compose.yaml" -f "$slot_dir/compose.override.yaml" "$@"
}
started=$(date +%s)
if ! compose up -d --pull never --wait --wait-timeout 300 world tools > "$slot_dir/up.log" 2>&1; then
  cat "$slot_dir/up.log" >&2
  compose logs --tail 30 world tools >&2 2>&1 || true
  compose down -v --remove-orphans -t 1 >> "$slot_dir/up.log" 2>&1 || true
  rm -f "$slot_dir/servers.json"
  die "slot $slot did not become healthy; containers removed (log: $slot_dir/up.log)"
fi
elapsed=$(( $(date +%s) - started ))

low=$((20000 + slot * 100 + 1))
printf 'slot %s up: %s healthy in %ss, project %s, tools on 127.0.0.1:%s-%s\n' \
  "$slot" "$(basename "$task_dir")" "$elapsed" "$project" "$low" "$((low + 31))"
printf 'agent prompt: %s\n' "$slot_dir/agent-prompt.md"
